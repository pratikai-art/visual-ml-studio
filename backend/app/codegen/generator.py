class CG:
    def __init__(self, wf: Workflow, hints: dict):
        self.wf, self.hints = wf, hints
        self.imports: set = set()
        self.cells: list = []  # (node_id, title, markdown, code)
        self.meta: dict = {}
        self.current: str = ""
        self._idx = {n.id: i + 1 for i, n in enumerate(wf.nodes)}

    def out(self, nid, port):
        return f"n{self._idx[nid]}"

    def cell(self, nid, title, md, code):
        self.cells.append((nid, title, md, code))

    def infer_task(self, sv, target):
        return self.hints.get(self.current, "regression")


def _resolve_hints(wf: Workflow) -> dict:
    """Resolve task='auto' of target nodes by running the (cached) upstream graph."""
    hints = {}
    autos = [n for n in wf.nodes if n.type == "select_target" and n.params.get("task", "auto") == "auto"]
    if not autos:
        return hints
    from ..workflow.executor import execute, new_job
    for n in autos:
        job = new_job(wf, n.id)
        execute(wf, job, threading.Event(), n.id)
        pv = job["nodes"][n.id].get("preview") or {}
        if pv.get("task"):
            hints[n.id] = pv["task"]
    return hints


def generate(wf: Workflow, only_node: str | None = None) -> CG:
    issues = [i for i in validate(wf) if i["level"] == "error"]
    if issues:
        raise NodeError("Fix these problems before generating code: " + " | ".join(i["message"] for i in issues[:5]))
    cg = CG(wf, _resolve_hints(wf))
    order = topo_order(wf)
    nodes = {n.id: n for n in wf.nodes}
    incoming = defaultdict(lambda: defaultdict(list))
    for e in wf.edges:
        incoming[e.target][e.targetHandle].append(e.source)
    produced: dict = {}
    for nid in order:
        n = nodes[nid]
        spec = REGISTRY[n.type]
        p, _ = validate_params(spec, n.params)
        ins = {port: [produced[s] for s in srcs] for port, srcs in incoming[nid].items()}
        cg.current = nid
        before = len(cg.cells)
        out = spec.codegen(cg, nid, p, ins)
        for port, var in (out or {}).items():
            produced[nid] = var
        if only_node and nid == only_node:
            cg.cells = cg.cells[before:]
            return cg
    return cg


BASE_IMPORTS = {"import numpy as np", "import pandas as pd", "import plotly.express as px", "from IPython.display import display"}


def _imports_block(cg: CG) -> str:
    imps = sorted(cg.imports | {"import numpy as np", "import pandas as pd", "from IPython.display import display"})
    plain = [i for i in imps if i.startswith("import ")]
    froms = [i for i in imps if i.startswith("from ")]
    return "import warnings\nwarnings.filterwarnings('ignore')\n\n" + "\n".join(plain + froms)


def to_script(wf: Workflow, only_node: str | None = None) -> str:
    cg = generate(wf, only_node)
    parts = [f'"""Generated by Visual ML Studio — {wf.name}.\nPython {"3.10+"}; install: pip install pandas numpy scikit-learn plotly ipython"""', _imports_block(cg), "SEED = 42\nnp.random.seed(SEED)"]
    for nid, title, md, code in cg.cells:
        parts.append(f"# %% {title}\n# {md.splitlines()[0] if md else ''}\n{code}")
    return "\n\n".join(parts) + "\n"


def to_notebook(wf: Workflow) -> nbformat.NotebookNode:
    cg = generate(wf)
    j = wf.journal or {}
    cells = [new_markdown_cell(f"# {wf.name}\n\nExported from **Visual ML Studio**. This notebook is self-contained: it does not depend on the web application.\n\n"
                               f"**Description:** {j.get('description') or 'Machine-learning experiment built visually.'}"),
             new_markdown_cell("## Research question / hypothesis\n\n" + (j.get("hypothesis") or "_Write your hypothesis here._")),
             new_markdown_cell("## Required libraries\n\n`pandas`, `numpy`, `scikit-learn`, `plotly`, `ipython`. Run the next cell once to install them if needed."),
             new_code_cell("# %pip install -q pandas numpy scikit-learn plotly"),
             new_code_cell(_imports_block(cg) + "\n\nSEED = 42\nnp.random.seed(SEED)")]
    for nid, title, md, code in cg.cells:
        cells.append(new_markdown_cell(f"## {title}\n\n{md}"))
        cells.append(new_code_cell(code))
    cells.append(new_markdown_cell("## Conclusions\n\n" + (j.get("conclusions") or "_Summarise what you learned. Compare results with your hypothesis._")
                                   + ("\n\n**Observations:** " + j["observations"] if j.get("observations") else "")))
    cells.append(new_markdown_cell("## Reproducibility notes\n\nRandom seeds are fixed inside every node. Package versions used when you run this notebook are printed below."))
    cells.append(new_code_cell("import sys, sklearn, plotly\nprint('python', sys.version.split()[0], '| pandas', pd.__version__, '| numpy', np.__version__, '| scikit-learn', sklearn.__version__, '| plotly', plotly.__version__)"))
    nb = new_notebook(cells=cells, metadata={"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                                              "language_info": {"name": "python"}})
    return nb


def validate_notebook(nb) -> dict:
    problems = []
    try:
        nbformat.validate(nb)
    except Exception as e:  # noqa: BLE001
        problems.append(f"Invalid notebook structure: {e}")
    n_code = 0
    for i, c in enumerate(nb.cells):
        if c.cell_type == "code":
            n_code += 1
            src = "\n".join(l for l in c.source.splitlines() if not l.lstrip().startswith(("%", "!")))
            try:
                ast.parse(src)
            except SyntaxError as e:
                problems.append(f"Cell {i}: syntax error line {e.lineno}: {e.msg}")
    text = "\n".join(c.source for c in nb.cells if c.cell_type == "code")
    for lib in ("pd.", "np."):
        if lib in text and {"pd.": "import pandas as pd", "np.": "import numpy as np"}[lib] not in text:
            problems.append(f"Missing import for {lib[:-1]}")
    return {"valid": not problems, "problems": problems, "cells": len(nb.cells), "code_cells": n_code}
