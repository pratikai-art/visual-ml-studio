def builtin_code(key: str, rows: int, seed: int) -> str:
    info = BUILTINS[key]
    return info["snippet"].format(rows=rows, seed=seed) if info.get("sized") else info["snippet"]


def load_builtin(key: str, rows: int = 300, seed: int = 42) -> pd.DataFrame:
    if key not in BUILTINS:
        raise KeyError(key)
    ns: dict = {}
    exec(compile(builtin_code(key, rows, seed), f"<builtin:{key}>", "exec"), ns)  # internal constant code only
    return ns["df"]


def catalog() -> list:
    return [{"key": k, **{f: v[f] for f in ("label", "task", "target", "source", "license")},
             "sized": bool(v.get("sized"))} for k, v in BUILTINS.items()]
